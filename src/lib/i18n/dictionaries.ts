export const DICTIONARIES: Record<Locale, Dict> = { en, id, zh };
/** Terjemahan + penggantian {param}. Kunci yang hilang jatuh ke bahasa Inggris
 *  alih-alih menampilkan kode kunci ke pengguna.
 *
 *  Ada DI SINI, bukan di `i18n/index.ts`, karena index memuat `next/headers`
 *  di tingkat modul — dan pengirim email berjalan di webhook dan skrip, tempat
 *  konteks permintaan tidak selalu ada. */
export function translate(locale: Locale, key: MessageKey, params?: Record<string, string | number>) {
  const raw = DICTIONARIES[locale]?.[key] ?? DICTIONARIES.en[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k: string) => String(params[k] ?? m));
}
